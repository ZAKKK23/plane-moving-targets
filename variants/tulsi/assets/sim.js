/* ===========================================================
   VTP — Moving Targets  |  live simulation
   Ported from the MATLAB model (dynamics.m / Target.m / alignTo.m /
   neighborhoods.m / voronoiProjectToBoundary.m). Runs the same
   Voronoi-neighbor repulsion + alignment + homing law, but target
   motion is generated by an explicit Tusi couple (two circles whose
   1:2 rolling makes a point trace a straight line) instead of the
   MATLAB build's bounce-in-a-box version.
   =========================================================== */

const TARGET_COLORS = ["#4c8bf5", "#f5a742", "#4cd97d", "#f2685f", "#c792ea", "#3fd0c9"];

const PARAMS = {
  N: 170,          // number of agents ("cells")
  NU_DEFAULT: 2.5,  // default alignment weight (live-editable: sim.nu)
  L_DEFAULT: 1,     // default interaction length scale (live-editable: sim.L)
  tarRad: 5,        // radius of the ring the target centers sit on
  RADIUS_BINS: [0, 1, 2, 3, 4, 6, 8, 11, 15, 20, Infinity],  // distance-from-target bin edges (snapshot profile chart)
  RADII: [1, 2, 3, 4, 5, 6, 8, 10, 13, 16],  // "within radius R" thresholds — one time-series chart each
  HISTORY_MAX: 300,  // how many past steps each on-screen mini-chart keeps
  EXPORT_RADIUS: 4,  // the radius the PNG export chart tracks
};

function expReciprocal(x) {
  if (x >= 1) return 0;
  return Math.exp(-1 / (1 - x)) / (Math.exp(-1 / x) + Math.exp(-1 / (1 - x)));
}
function norm2(v) { return Math.hypot(v[0], v[1]); }
function unit(v) {
  const n = norm2(v);
  return n < 1e-12 ? [0, 0] : [v[0] / n, v[1] / n];
}
function clamp(x, a, b) { return Math.max(a, Math.min(b, x)); }

class VTPSim {
  constructor(canvas, nT = 6) {
    this.canvas = canvas;
    this.ctx = canvas.getContext("2d");
    this.cellSpd = 1.0;
    this.amp = 7.0;
    this.nu = PARAMS.NU_DEFAULT;   // alignment weight — live-editable
    this.L = PARAMS.L_DEFAULT;     // interaction length scale — live-editable
    this.paused = false;
    this.t = 0;
    this.cam = null; // {cx,cy,hw} smoothed camera
    this.setup(nT);
  }

  setup(nT) {
    nT = clamp(Math.round(nT), 1, 6);
    this.nT = nT;
    const N = PARAMS.N;

    // ---- agents ----
    const icRad = 0.5 * Math.sqrt((N * Math.PI) / 4 / 0.91);
    this.X = new Float64Array(N * 2);
    this.U = new Float64Array(N * 2);
    for (let i = 0; i < N; i++) {
      this.X[2 * i] = icRad * (2 * Math.random() - 1);
      this.X[2 * i + 1] = icRad * (2 * Math.random() - 1);
      const a = 2 * Math.PI * Math.random();
      this.U[2 * i] = Math.cos(a);
      this.U[2 * i + 1] = Math.sin(a);
    }

    // ---- targets: Tusi-couple oscillators ----
    this.targets = [];
    for (let k = 0; k < nT; k++) {
      const ang = (2 * Math.PI / nT) * k;
      this.targets.push({
        cx: PARAMS.tarRad * Math.cos(ang),
        cy: PARAMS.tarRad * Math.sin(ang),
        lineDeg: Math.round(Math.random() * 360 * 10) / 10,
        omega: 0.05,
        phase: Math.random() * Math.PI * 2,
      });
    }
    this.t = 0;
    this.cam = null;
    this.hist = this.targets.map(() => new Array(PARAMS.RADIUS_BINS.length - 1).fill(0));
    this.nearCounts = PARAMS.RADII.map(() => new Array(nT).fill(0));   // [radiusIdx][targetIdx]
    this.history = PARAMS.RADII.map(() => Array.from({ length: nT }, () => []));  // [radiusIdx][targetIdx] -> time series
    this.historyT = [];
    // Long-running, uncapped log of "agents within PARAMS.EXPORT_RADIUS of
    // each target" — kept separate from the rolling on-screen history above
    // so the exported chart can cover the whole run, not just the last
    // HISTORY_MAX steps.
    this.longHistory = Array.from({ length: nT }, () => []);
    this.longHistoryT = [];
    this.onSetupChange && this.onSetupChange(this.targets);
  }

  targetPos(tg) {
    const th = (tg.lineDeg * Math.PI) / 180;
    const d = Math.cos(tg.phase) * this.amp;
    return [tg.cx + d * Math.cos(th), tg.cy + d * Math.sin(th)];
  }
  targetSmallCircleCenter(tg) {
    const th = (tg.lineDeg * Math.PI) / 180;
    const r = this.amp / 2;
    const d = Math.cos(tg.phase) * r;
    return [tg.cx + d * Math.cos(th), tg.cy + d * Math.sin(th)];
  }

  step() {
    if (this.paused) return;
    this.t++;

    for (const tg of this.targets) tg.phase += tg.omega;

    const N = PARAMS.N;
    const X = this.X, U = this.U;
    const pts = new Array(N);
    for (let i = 0; i < N; i++) pts[i] = [X[2 * i], X[2 * i + 1]];

    const delaunay = d3.Delaunay.from(pts);
    const tpos = this.targets.map((tg) => this.targetPos(tg));

    const newU = new Float64Array(N * 2);
    const nu = this.nu, L = this.L;

    for (let i = 0; i < N; i++) {
      const xi = [X[2 * i], X[2 * i + 1]];
      const neighbors = [...delaunay.neighbors(i)];

      // nearest neighbor + distance
      let dmin = Infinity, nearest = -1;
      for (const j of neighbors) {
        const dx = xi[0] - X[2 * j], dy = xi[1] - X[2 * j + 1];
        const d = Math.hypot(dx, dy);
        if (d < dmin) { dmin = d; nearest = j; }
      }
      if (nearest === -1) { newU[2 * i] = U[2 * i]; newU[2 * i + 1] = U[2 * i + 1]; continue; }

      const s = expReciprocal(dmin / L);

      // repulsion, away from nearest neighbor
      const rrep = unit([xi[0] - X[2 * nearest], xi[1] - X[2 * nearest + 1]]);

      // alignment over Delaunay neighbors
      const ui = unit([U[2 * i], U[2 * i + 1]]);
      let ax = 0, ay = 0;
      for (const j of neighbors) {
        const uj = unit([U[2 * j], U[2 * j + 1]]);
        let dot = ui[0] * uj[0] + ui[1] * uj[1];
        dot = clamp(dot, -1, 1);
        const w = expReciprocal(Math.acos(dot) / Math.PI);
        ax += w * uj[0]; ay += w * uj[1];
      }
      ax /= 6; ay /= 6;

      // homing to nearest target
      let hbest = null, hbestD = Infinity;
      for (const tp of tpos) {
        const v = [tp[0] - xi[0], tp[1] - xi[1]];
        const d2 = v[0] * v[0] + v[1] * v[1];
        if (d2 < hbestD) { hbestD = d2; hbest = v; }
      }
      const hdir = unit(hbest);
      const h = [(1 - s) * hdir[0], (1 - s) * hdir[1]];

      const u1x = (s * rrep[0] + h[0] + nu * ax) / (1 + nu);
      const u1y = (s * rrep[1] + h[1] + nu * ay) / (1 + nu);

      // speed cap: approximates the MATLAB Voronoi ray-to-boundary projection
      // by half the distance to the nearest Delaunay neighbor.
      const M = 0.5 * dmin;
      const speedFactor = this.cellSpd * Math.tanh(M / this.L);

      newU[2 * i] = speedFactor * u1x;
      newU[2 * i + 1] = speedFactor * u1y;
    }

    for (let i = 0; i < N; i++) {
      U[2 * i] = newU[2 * i]; U[2 * i + 1] = newU[2 * i + 1];
      X[2 * i] += U[2 * i]; X[2 * i + 1] += U[2 * i + 1];
    }

    this.updateStats(tpos);
  }

  // For every target: how many agents fall in each distance ring
  // (RADIUS_BINS), plus — for every threshold in RADII — how many agents
  // are currently within that radius. Each RADII[r] value gets its own
  // rolling per-target time series (this.history[r][k]).
  updateStats(tpos) {
    const N = PARAMS.N;
    const nT = this.targets.length;
    const bins = PARAMS.RADIUS_BINS;
    const radii = PARAMS.RADII;
    const hist = Array.from({ length: nT }, () => new Array(bins.length - 1).fill(0));
    const nearCounts = radii.map(() => new Array(nT).fill(0));  // [radiusIdx][targetIdx]

    for (let i = 0; i < N; i++) {
      const x = this.X[2 * i], y = this.X[2 * i + 1];
      for (let k = 0; k < nT; k++) {
        const dx = x - tpos[k][0], dy = y - tpos[k][1];
        const d = Math.hypot(dx, dy);
        for (let b = 0; b < bins.length - 1; b++) {
          if (d >= bins[b] && d < bins[b + 1]) { hist[k][b]++; break; }
        }
        for (let r = 0; r < radii.length; r++) {
          if (d <= radii[r]) nearCounts[r][k]++;
        }
      }
    }

    this.hist = hist;
    this.nearCounts = nearCounts;
    this.historyT.push(this.t);
    for (let r = 0; r < radii.length; r++) {
      for (let k = 0; k < nT; k++) this.history[r][k].push(nearCounts[r][k]);
    }
    if (this.historyT.length > PARAMS.HISTORY_MAX) {
      this.historyT.shift();
      for (let r = 0; r < radii.length; r++) {
        for (let k = 0; k < nT; k++) this.history[r][k].shift();
      }
    }

    // long-running, uncapped log for PARAMS.EXPORT_RADIUS only
    const exportIdx = radii.indexOf(PARAMS.EXPORT_RADIUS);
    if (exportIdx !== -1) {
      this.longHistoryT.push(this.t);
      for (let k = 0; k < nT; k++) this.longHistory[k].push(nearCounts[exportIdx][k]);
    }
  }

  updateCamera() {
    const N = PARAMS.N;
    const X = this.X;
    let sx = 0, sy = 0;
    for (let i = 0; i < N; i++) { sx += X[2 * i]; sy += X[2 * i + 1]; }
    const cx0 = sx / N, cy0 = sy / N;
    let ss = 0;
    for (let i = 0; i < N; i++) {
      const dx = X[2 * i] - cx0, dy = X[2 * i + 1] - cy0;
      ss += dx * dx + dy * dy;
    }
    const rmed = Math.sqrt(ss / N);
    let hw = Math.max(3 * rmed, this.amp + PARAMS.tarRad * 0.6);

    let xlo = cx0 - hw, xhi = cx0 + hw, ylo = cy0 - hw, yhi = cy0 + hw;
    for (const tg of this.targets) {
      xlo = Math.min(xlo, tg.cx - this.amp - 1);
      xhi = Math.max(xhi, tg.cx + this.amp + 1);
      ylo = Math.min(ylo, tg.cy - this.amp - 1);
      yhi = Math.max(yhi, tg.cy + this.amp + 1);
    }
    const hw2 = Math.max(xhi - xlo, yhi - ylo) / 2;
    const cx2 = (xlo + xhi) / 2, cy2 = (ylo + yhi) / 2;

    if (!this.cam) this.cam = { cx: cx2, cy: cy2, hw: hw2 };
    const a = 0.05;
    this.cam.cx += (cx2 - this.cam.cx) * a;
    this.cam.cy += (cy2 - this.cam.cy) * a;
    this.cam.hw += (hw2 - this.cam.hw) * a;
  }

  draw() {
    const canvas = this.canvas, ctx = this.ctx;
    const dpr = window.devicePixelRatio || 1;
    const w = canvas.clientWidth, h = canvas.clientHeight;
    if (canvas.width !== w * dpr || canvas.height !== h * dpr) {
      canvas.width = w * dpr; canvas.height = h * dpr;
    }
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, w, h);

    this.updateCamera();
    const { cx, cy, hw } = this.cam;
    const scale = Math.min(w, h) / (2 * hw);
    const toPx = (x, y) => [w / 2 + (x - cx) * scale, h / 2 - (y - cy) * scale];

    // targets: diameter line + labeled dot (no Tusi-couple circles)
    for (let k = 0; k < this.targets.length; k++) {
      const tg = this.targets[k];
      const col = TARGET_COLORS[k % TARGET_COLORS.length];
      const th = (tg.lineDeg * Math.PI) / 180;

      // diameter line
      const [lx1, ly1] = toPx(tg.cx - this.amp * 1.15 * Math.cos(th), tg.cy - this.amp * 1.15 * Math.sin(th));
      const [lx2, ly2] = toPx(tg.cx + this.amp * 1.15 * Math.cos(th), tg.cy + this.amp * 1.15 * Math.sin(th));
      ctx.strokeStyle = col; ctx.globalAlpha = 0.55; ctx.lineWidth = 1;
      ctx.beginPath(); ctx.moveTo(lx1, ly1); ctx.lineTo(lx2, ly2); ctx.stroke();
      ctx.globalAlpha = 1;

      // target point
      const [tx, ty] = toPx(...this.targetPos(tg));
      ctx.fillStyle = col;
      ctx.beginPath(); ctx.arc(tx, ty, 9, 0, Math.PI * 2); ctx.fill();
      ctx.fillStyle = "#0a0c12";
      ctx.font = "700 9px " + getComputedStyle(document.body).getPropertyValue("--mono");
      ctx.textAlign = "center"; ctx.textBaseline = "middle";
      ctx.fillText("T" + (k + 1), tx, ty + 0.5);
    }

    // agents: dot + velocity arrow
    const N = PARAMS.N;
    ctx.fillStyle = "#f4f5f7";
    for (let i = 0; i < N; i++) {
      const [px, py] = toPx(this.X[2 * i], this.X[2 * i + 1]);
      ctx.beginPath(); ctx.arc(px, py, 2, 0, Math.PI * 2); ctx.fill();
    }
    ctx.strokeStyle = "#5aa4f2"; ctx.fillStyle = "#5aa4f2"; ctx.lineWidth = 1;
    ctx.globalAlpha = 0.85;
    const vscale = 4.2;
    for (let i = 0; i < N; i++) {
      const x0 = this.X[2 * i], y0 = this.X[2 * i + 1];
      const ux = this.U[2 * i], uy = this.U[2 * i + 1];
      const [px0, py0] = toPx(x0, y0);
      const [px1, py1] = toPx(x0 + ux * vscale, y0 + uy * vscale);
      ctx.beginPath(); ctx.moveTo(px0, py0); ctx.lineTo(px1, py1); ctx.stroke();
      const ang = Math.atan2(py1 - py0, px1 - px0);
      ctx.beginPath();
      ctx.moveTo(px1, py1);
      ctx.lineTo(px1 - 4.5 * Math.cos(ang - 0.4), py1 - 4.5 * Math.sin(ang - 0.4));
      ctx.lineTo(px1 - 4.5 * Math.cos(ang + 0.4), py1 - 4.5 * Math.sin(ang + 0.4));
      ctx.closePath(); ctx.fill();
    }
    ctx.globalAlpha = 1;
  }

  // ---- shared low-level chart helpers -------------------------------
  _prepCanvas(canvas) {
    const ctx = canvas.getContext("2d");
    const dpr = window.devicePixelRatio || 1;
    const cw = canvas.clientWidth, ch = canvas.clientHeight;
    let w, h;
    if (cw > 0 && ch > 0) {
      // on-screen canvas: keep its backing store in sync with its laid-out CSS size
      w = cw; h = ch;
      if (canvas.width !== w * dpr || canvas.height !== h * dpr) {
        canvas.width = w * dpr; canvas.height = h * dpr;
      }
      ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    } else {
      // detached/offscreen canvas (e.g. built for a PNG export): clientWidth/
      // Height read 0 since it was never laid out, so just use whatever
      // width/height was already set on it directly.
      w = canvas.width; h = canvas.height;
      ctx.setTransform(1, 0, 0, 1, 0, 0);
    }
    ctx.clearRect(0, 0, w, h);
    return { ctx, w, h };
  }
  _drawAxes(ctx, x0, y0, pw, ph, yMax) {
    ctx.strokeStyle = "#1c1f29"; ctx.lineWidth = 1;
    ctx.beginPath(); ctx.moveTo(x0, y0); ctx.lineTo(x0, y0 + ph); ctx.lineTo(x0 + pw, y0 + ph); ctx.stroke();
    const ticks = 4;
    for (let i = 0; i <= ticks; i++) {
      const v = Math.round((yMax * i) / ticks);
      const py = y0 + ph - (ph * i) / ticks;
      ctx.strokeStyle = "#14161d"; ctx.beginPath(); ctx.moveTo(x0, py); ctx.lineTo(x0 + pw, py); ctx.stroke();
      ctx.fillStyle = "#7b8394"; ctx.textAlign = "right"; ctx.textBaseline = "middle";
      ctx.fillText(String(v), x0 - 5, py);
    }
  }

  // Snapshot: agent count vs. distance-from-target, one curve per target.
  drawProfileChart(canvas) {
    if (!this.hist) return;
    const { ctx, w, h } = this._prepCanvas(canvas);
    const mono = getComputedStyle(document.body).getPropertyValue("--mono");
    const padL = 34, padR = 12, padT = 22, padB = 22;
    const x0 = padL, y0 = padT, pw = w - padL - padR, ph = h - padT - padB;
    const nT = this.targets.length;
    const bins = PARAMS.RADIUS_BINS;
    const nBins = bins.length - 1;

    let yMax = 1;
    for (let k = 0; k < nT; k++) for (const c of this.hist[k]) yMax = Math.max(yMax, c);
    yMax = Math.ceil(yMax * 1.15);

    ctx.font = "10px " + mono;
    this._drawAxes(ctx, x0, y0, pw, ph, yMax);
    ctx.fillStyle = "#a8adb8"; ctx.textAlign = "center"; ctx.textBaseline = "bottom";
    ctx.fillText("agents by distance from target (snapshot)", x0 + pw / 2, y0 - 6);

    ctx.font = "9px " + mono; ctx.textBaseline = "top";
    for (let i = 0; i <= nBins; i++) {
      if (i % 2 !== 0 && i !== nBins) continue;
      const edge = bins[i] === Infinity ? bins[i - 1] : bins[i];
      const px = x0 + (pw * i) / nBins;
      ctx.fillStyle = "#5a6070";
      ctx.fillText(i === nBins ? edge + "+" : String(edge), px, y0 + ph + 2);
    }
    ctx.font = "10px " + mono;

    const xAt = (i) => x0 + (pw * (i + 0.5)) / nBins;
    for (let k = 0; k < nT; k++) {
      const col = TARGET_COLORS[k % TARGET_COLORS.length];
      ctx.strokeStyle = col; ctx.lineWidth = 1.6; ctx.globalAlpha = 0.9;
      ctx.beginPath();
      this.hist[k].forEach((c, i) => {
        const px = xAt(i), py = y0 + ph - (ph * c) / yMax;
        if (i === 0) ctx.moveTo(px, py); else ctx.lineTo(px, py);
      });
      ctx.stroke();
      ctx.globalAlpha = 1;
      let peak = 0;
      for (let i = 1; i < this.hist[k].length; i++) if (this.hist[k][i] > this.hist[k][peak]) peak = i;
      const lx = xAt(peak), ly = y0 + ph - (ph * this.hist[k][peak]) / yMax;
      ctx.fillStyle = col; ctx.textAlign = "center"; ctx.textBaseline = "bottom";
      ctx.fillText("T" + (k + 1), lx, ly - 3);
    }
  }

  // Time series for one radius threshold (PARAMS.RADII[radiusIdx]): agent
  // count within that radius of each target, over the recent history window.
  drawRadiusChart(canvas, radiusIdx) {
    if (!this.history) return;
    const { ctx, w, h } = this._prepCanvas(canvas);
    const mono = getComputedStyle(document.body).getPropertyValue("--mono");
    const padL = 30, padR = 8, padT = 20, padB = 8;
    const x0 = padL, y0 = padT, pw = w - padL - padR, ph = h - padT - padB;
    const nT = this.targets.length;
    const R = PARAMS.RADII[radiusIdx];
    const series = this.history[radiusIdx];

    let yMax = 1;
    for (let k = 0; k < nT; k++) for (const c of series[k]) yMax = Math.max(yMax, c);
    yMax = Math.ceil(yMax * 1.15);

    ctx.font = "9px " + mono;
    this._drawAxes(ctx, x0, y0, pw, ph, yMax);
    ctx.fillStyle = "#a8adb8"; ctx.textAlign = "left"; ctx.textBaseline = "bottom";
    ctx.fillText(`within radius ${R}`, x0, y0 - 5);

    const n = this.historyT.length;
    if (n > 1) {
      const xAt = (i) => x0 + (pw * i) / (PARAMS.HISTORY_MAX - 1);
      const offset = PARAMS.HISTORY_MAX - n;
      for (let k = 0; k < nT; k++) {
        const col = TARGET_COLORS[k % TARGET_COLORS.length];
        ctx.strokeStyle = col; ctx.lineWidth = 1.4; ctx.globalAlpha = 0.9;
        ctx.beginPath();
        series[k].forEach((c, i) => {
          const px = xAt(offset + i), py = y0 + ph - (ph * c) / yMax;
          if (i === 0) ctx.moveTo(px, py); else ctx.lineTo(px, py);
        });
        ctx.stroke();
        ctx.globalAlpha = 1;
      }
    }
  }

  // The full, uncapped time series for PARAMS.EXPORT_RADIUS — covers the
  // whole run (not just the last HISTORY_MAX steps), for the PNG export.
  // Sized generously by default since it's meant for a downloaded image,
  // not the small on-screen grid.
  drawLongRadiusChart(canvas) {
    if (!this.longHistory) return;
    const { ctx, w, h } = this._prepCanvas(canvas);
    ctx.fillStyle = "#05060a";
    ctx.fillRect(0, 0, w, h);
    const mono = getComputedStyle(document.body).getPropertyValue("--mono");
    const padL = 46, padR = 16, padT = 34, padB = 30;
    const x0 = padL, y0 = padT, pw = w - padL - padR, ph = h - padT - padB;
    const nT = this.targets.length;
    const n = this.longHistoryT.length;

    let yMax = 1;
    for (let k = 0; k < nT; k++) for (const c of this.longHistory[k]) yMax = Math.max(yMax, c);
    yMax = Math.ceil(yMax * 1.15);

    ctx.font = "13px " + mono;
    this._drawAxes(ctx, x0, y0, pw, ph, yMax);
    ctx.fillStyle = "#e8ecf2"; ctx.textAlign = "left"; ctx.textBaseline = "bottom";
    ctx.fillText(`agents within radius ${PARAMS.EXPORT_RADIUS} of each target — full run (${n} steps)`, x0, y0 - 10);

    if (n > 1) {
      const tMin = this.longHistoryT[0], tMax = this.longHistoryT[n - 1];
      const span = Math.max(1, tMax - tMin);
      const xAt = (t) => x0 + (pw * (t - tMin)) / span;

      // time-axis tick labels
      ctx.font = "11px " + mono; ctx.fillStyle = "#7b8394";
      ctx.textAlign = "center"; ctx.textBaseline = "top";
      const ticks = 6;
      for (let i = 0; i <= ticks; i++) {
        const t = Math.round(tMin + (span * i) / ticks);
        ctx.fillText("t=" + t, x0 + (pw * i) / ticks, y0 + ph + 6);
      }
      ctx.font = "13px " + mono;

      for (let k = 0; k < nT; k++) {
        const col = TARGET_COLORS[k % TARGET_COLORS.length];
        ctx.strokeStyle = col; ctx.lineWidth = 1.8; ctx.globalAlpha = 0.9;
        ctx.beginPath();
        this.longHistory[k].forEach((c, i) => {
          const px = xAt(this.longHistoryT[i]), py = y0 + ph - (ph * c) / yMax;
          if (i === 0) ctx.moveTo(px, py); else ctx.lineTo(px, py);
        });
        ctx.stroke();
        ctx.globalAlpha = 1;
        const lastC = this.longHistory[k][n - 1];
        ctx.fillStyle = col; ctx.textAlign = "left"; ctx.textBaseline = "middle";
        ctx.fillText("T" + (k + 1), Math.min(xAt(this.longHistoryT[n - 1]) + 5, x0 + pw - 20), y0 + ph - (ph * lastC) / yMax);
      }
    }
  }

  // Downloads the full per-radius, per-target time series collected so far
  // as a CSV (wide format: one row per step, one column per radius+target).
  exportCSV() {
    const nT = this.targets.length;
    const radii = PARAMS.RADII;
    const header = ["t"];
    for (const r of radii) for (let k = 0; k < nT; k++) header.push(`r${r}_T${k + 1}`);
    const lines = [header.join(",")];
    for (let i = 0; i < this.historyT.length; i++) {
      const row = [this.historyT[i]];
      for (let r = 0; r < radii.length; r++) {
        for (let k = 0; k < nT; k++) row.push(this.history[r][k][i]);
      }
      lines.push(row.join(","));
    }
    const csv = lines.join("\n");
    const blob = new Blob([csv], { type: "text/csv" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `vtp-near-counts-t${this.t}.csv`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }
}
